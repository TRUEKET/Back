-- Apply manually to Supabase before starting the application.
ALTER TABLE users ADD COLUMN IF NOT EXISTS privacy_agreed_at timestamptz;
CREATE TABLE IF NOT EXISTS phone_verifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone_hash varchar(255) NOT NULL,
    purpose varchar(40) NOT NULL
        CHECK (purpose IN ('SIGNUP', 'REPORT') OR purpose ~ '^PHONE_CHANGE:[0-9]+$'),
    code_hash varchar(255) NOT NULL,
    expires_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    verified_at timestamptz,
    consumed_at timestamptz,
    attempt_count integer NOT NULL DEFAULT 0,
    UNIQUE (phone_hash, purpose)
);
ALTER TABLE phone_verifications ENABLE ROW LEVEL SECURITY;

-- Existing team table requires this field to prevent reuse after signup.
ALTER TABLE public.phone_verifications ADD COLUMN IF NOT EXISTS consumed_at timestamptz;
